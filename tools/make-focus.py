#!/usr/bin/env python3
"""
Where each creature sits in its portrait, from its cut-out mask: the box the NFT card frames.

Input:  art/masks/<id>.png (see cut-masks.py), cleaned like make-sprites.py does
Output: apps/api/src/modules/nft/focus.ts  — box per creature as fractions of the portrait
Run from the repo root: python3 tools/make-focus.py
"""
import importlib.util
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("make_sprites", ROOT / "tools" / "make-sprites.py")
sprites = importlib.util.module_from_spec(spec)
spec.loader.exec_module(sprites)

OUT = ROOT / "apps" / "api" / "src" / "modules" / "nft" / "focus.ts"


def main():
    lines = []
    for mask in sorted((ROOT / "art" / "masks").glob("*.png")):
        cid = mask.stem
        portrait = Image.open(ROOT / "apps" / "web" / "public" / "creatures" / f"{cid}.webp")
        m = np.asarray(Image.open(mask).convert("L").resize(portrait.size))
        a = sprites.clean_mask(m, sprites.SOFT_MASK.get(cid, 0.2))
        ys, xs = np.nonzero(a > 0.5)
        h, w = a.shape
        box = (xs.min() / w, ys.min() / h, (xs.max() + 1) / w, (ys.max() + 1) / h)
        lines.append(f"  {cid}: [{', '.join(f'{v:.3f}' for v in box)}],")
    OUT.write_text(
        "// Generated by tools/make-focus.py from the cut-out masks. Do not edit by hand.\n"
        "/** Where each creature sits in its portrait: [left, top, right, bottom], 0–1. */\n"
        "export const FOCUS: Record<string, readonly [number, number, number, number]> = {\n"
        + "\n".join(lines)
        + "\n};\n"
    )
    print(f"{len(lines)} boxes → {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
